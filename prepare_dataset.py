"""
Convert a COCO-annotated dataset into YOLO training format using this project's
canonical class scheme.

Emits:
    <out>/images/{train,val}/   hardlinks to the source images (no duplication)
    <out>/labels/{train,val}/   YOLO txt: "<cls> <cx> <cy> <w> <h>" normalised
    <out>/data.yaml             dataset descriptor for ultralytics
    <out>/val_coco.json         COCO file for the val split, so eval_detection.py
                                can score before/after on the SAME held-out images

Class handling mirrors eval_detection.py so training and evaluation cannot drift
apart: the mapping is imported from there rather than restated.

NOTE ON EXCLUDED CLASSES: boxes whose dataset class has no canonical equivalent
(three-wheelers) are dropped from the labels. YOLO has no "ignore region"
concept, so a dropped box is not neutral -- it becomes *background*, and the
model is actively trained to NOT fire there. On this data that is 17% of all
vehicles. See the warning printed at the end.
"""

import argparse
import json
import os
import random
import shutil
from collections import Counter, defaultdict
from pathlib import Path

from detect_track import CANONICAL_CLASSES
from eval_detection import ASSUMED_MAP, DATASET_MAP, UNMATCHABLE

CLASS_INDEX = {name: i for i, name in enumerate(CANONICAL_CLASSES)}


def parse_args():
    p = argparse.ArgumentParser(
        description="COCO -> YOLO conversion with canonical class mapping.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument("--images", default="data/bmd45/images")
    p.add_argument("--annotations", default="data/bmd45/annotations.coco.json")
    p.add_argument("--out", default="data/bmd45_yolo")
    p.add_argument("--val-frac", type=float, default=0.2)
    p.add_argument("--seed", type=int, default=20260813)
    return p.parse_args()


def link_or_copy(src, dst):
    """Hardlink to avoid duplicating 3 MB PNGs; fall back to copying."""
    if dst.exists():
        return
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def main():
    args = parse_args()
    coco = json.load(open(args.annotations, encoding="utf-8"))
    cid2name = {c["id"]: c["name"] for c in coco["categories"]}
    img_dir = Path(args.images)
    out = Path(args.out)

    ann_by_img = defaultdict(list)
    for a in coco["annotations"]:
        ann_by_img[a["image_id"]].append(a)

    images = [im for im in coco["images"] if (img_dir / im["file_name"]).exists()]
    random.seed(args.seed)
    random.shuffle(images)
    n_val = max(1, round(len(images) * args.val_frac))
    splits = {"val": images[:n_val], "train": images[n_val:]}

    for sub in ("images", "labels"):
        for sp in splits:
            (out / sub / sp).mkdir(parents=True, exist_ok=True)

    counts = {sp: Counter() for sp in splits}
    dropped = {sp: Counter() for sp in splits}
    empty_labels = {sp: 0 for sp in splits}

    for sp, imgs in splits.items():
        for im in imgs:
            W, H = im["width"], im["height"]
            lines = []
            for a in ann_by_img[im["id"]]:
                name = cid2name[a["category_id"]]
                if name in UNMATCHABLE or name not in DATASET_MAP:
                    dropped[sp][name] += 1
                    continue
                canon = DATASET_MAP[name]
                x, y, w, h = a["bbox"]
                # clip to frame; a box escaping the image yields a bad target
                x0, y0 = max(0.0, x), max(0.0, y)
                x1, y1 = min(float(W), x + w), min(float(H), y + h)
                if x1 - x0 <= 1 or y1 - y0 <= 1:
                    continue
                cx, cy = (x0 + x1) / 2 / W, (y0 + y1) / 2 / H
                bw, bh = (x1 - x0) / W, (y1 - y0) / H
                lines.append(f"{CLASS_INDEX[canon]} {cx:.6f} {cy:.6f} "
                             f"{bw:.6f} {bh:.6f}")
                counts[sp][canon] += 1

            stem = Path(im["file_name"]).stem
            link_or_copy(img_dir / im["file_name"],
                         out / "images" / sp / im["file_name"])
            (out / "labels" / sp / f"{stem}.txt").write_text(
                "\n".join(lines), encoding="utf-8")
            if not lines:
                empty_labels[sp] += 1

    # data.yaml
    yaml_text = (
        f"# Generated by prepare_dataset.py -- do not edit by hand.\n"
        f"path: {out.resolve().as_posix()}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"nc: {len(CANONICAL_CLASSES)}\n"
        f"names:\n"
        + "".join(f"  {i}: {n}\n" for i, n in enumerate(CANONICAL_CLASSES))
    )
    (out / "data.yaml").write_text(yaml_text, encoding="utf-8")

    # val split as COCO, so eval_detection.py scores before/after on the same
    # held-out images (its own mapping/exclusion logic still applies).
    val_ids = {im["id"] for im in splits["val"]}
    val_coco = {
        "info": {**coco.get("info", {}),
                 "subset_note": f"val split ({len(val_ids)} images), seed {args.seed}"},
        "licenses": coco.get("licenses", []),
        "images": splits["val"],
        "annotations": [a for a in coco["annotations"] if a["image_id"] in val_ids],
        "categories": coco["categories"],
    }
    (out / "val_coco.json").write_text(json.dumps(val_coco), encoding="utf-8")

    # ---- report --------------------------------------------------------
    print(f"train images: {len(splits['train'])}   val images: {len(splits['val'])}")
    print(f"\n{'class':<10}{'train':>10}{'val':>10}")
    print("-" * 30)
    for c in CANONICAL_CLASSES:
        print(f"{c:<10}{counts['train'][c]:>10,}{counts['val'][c]:>10,}")
    print(f"{'TOTAL':<10}{sum(counts['train'].values()):>10,}"
          f"{sum(counts['val'].values()):>10,}")

    tot_drop = sum(sum(d.values()) for d in dropped.values())
    tot_keep = sum(sum(c.values()) for c in counts.values())
    if tot_drop:
        print(f"\nDropped (no canonical class): {tot_drop:,} boxes")
        for sp in splits:
            for name, n in dropped[sp].most_common():
                print(f"   {sp:<6}{name:<18}{n:>7,}")
        print(f"\n  !! WARNING: those {tot_drop:,} boxes "
              f"({100*tot_drop/(tot_drop+tot_keep):.1f}% of all vehicles) become "
              f"BACKGROUND\n     in training. The model is being taught not to fire "
              f"on them. If three-\n     wheelers matter, add them as a 5th class "
              f"instead of excluding them.")
    for sp in splits:
        if empty_labels[sp]:
            print(f"\n  note: {empty_labels[sp]} {sp} image(s) have no labels at all")

    if sum(counts['train'].values()) and min(
            counts['train'][c] for c in CANONICAL_CLASSES) < 50:
        thin = [c for c in CANONICAL_CLASSES if counts['train'][c] < 50]
        print(f"\n  !! WARNING: under 50 training boxes for: {', '.join(thin)}."
              f"\n     Fine-tuning cannot learn a class from that few examples; "
              f"expect it\n     to get worse, not better, on those.")

    print(f"\nWrote {out / 'data.yaml'}")
    print(f"Wrote {out / 'val_coco.json'}")


if __name__ == "__main__":
    main()
